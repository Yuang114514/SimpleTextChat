package cn.yuang2714.simple_text_chat;

import com.google.gson.JsonObject;
import com.google.gson.JsonParser;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;

public class STCCodeGenerator {
    static void main(String[] args) throws IOException {
        JsonObject translationEN = JsonParser.parseString(
                Files.readString(Path.of(args[0]))
        ).getAsJsonObject();
        
        var entries = translationEN.entrySet();
        
        StringBuilder codeBuilder = new StringBuilder("/**\n * all translation keys, generated by Codegen.\n */\npublic enum AllTranslations {\n");
        for (var entry : entries) {
            if (entry.getKey().contains("modmenu")) continue;
            
            codeBuilder
                    .append("    ")
                    .append(entry.getKey().replace(".", "_").toUpperCase().replace("_TEXT_CHAT_", "_"))
                    .append("(\"").append(entry.getKey()).append("\"),\n");
        }
        codeBuilder.append("""
                                       ;
                                   
                                       public final Component msg;
                                   
                                       AllTranslations(String key) {
                                           msg = VersionDifferences.translatableComponent(key);
                                       }
                                   }
                                   """);
        
        IO.println(codeBuilder);
    }
}
